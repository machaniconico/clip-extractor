def resolve_authoritative_cues(
    highlight: Mapping[str, Any],
    fallback: Sequence[AuthoritativeCue] = AUTHORITATIVE_CUES,
) -> tuple[Any, ...]:
    """Resolve cues without treating an explicit empty list as missing.

    The distinction is intentional: a missing field may use the fixed local
    context, whereas ``se_cues: []`` is an authoritative request for no SE.
    """

    if "se_cues" in highlight:
        value = highlight["se_cues"]
        if value is None:
            raise HarnessError("explicit se_cues must be a sequence, not None")
        if isinstance(value, (str, bytes)) or not isinstance(value, Sequence):
            raise HarnessError("explicit se_cues must be a sequence")
        return tuple(value)
    return tuple(fallback)


