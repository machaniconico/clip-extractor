def _number(value: Any, field: str) -> float:
    if type(value) not in (int, float):
        raise HarnessError(f"{field} must be an int or float, not {type(value).__name__}")
    number = float(value)
    if not math.isfinite(number):
        raise HarnessError(f"{field} must be finite")
    return number


def _probe_number(value: Any, field: str) -> float:
    """Parse ffprobe's JSON numeric strings without weakening report validation."""
    if type(value) in (int, float):
        number = float(value)
    elif isinstance(value, str) and value.strip():
        try:
            number = float(value)
        except ValueError as exc:
            raise HarnessError(f"{field} must be a finite ffprobe number") from exc
    else:
        raise HarnessError(f"{field} must be a finite ffprobe number")
    if not math.isfinite(number):
        raise HarnessError(f"{field} must be finite")
    return number


def _fresh_root(path: str | os.PathLike[str]) -> Path:
    candidate = Path(path).expanduser()
    if not candidate.is_absolute():
        candidate = Path.cwd() / candidate
    if not candidate.parent.exists():
        raise HarnessError("the supplied output root must have an existing parent")
    if candidate.exists():
        if candidate.is_symlink() or not candidate.is_dir():
            raise HarnessError("the supplied output root must be a regular directory")
        if any(candidate.iterdir()):
            raise HarnessError("the supplied output root must be fresh and empty")
    else:
        candidate.mkdir()
    return candidate.resolve(strict=True)


def _resolve_media_tools() -> dict[str, Path]:
    resolved: dict[str, Path] = {}
    for name in ("ffmpeg", "ffprobe"):
        found = shutil.which(name)
        if not found:
            raise HarnessError(f"required local executable is unavailable: {name}")
        path = Path(found).resolve(strict=True)
        if not path.is_file():
            raise HarnessError(f"resolved executable is not a regular file: {path}")
        resolved[name] = path
    if resolved["ffmpeg"] == resolved["ffprobe"]:
        raise HarnessError("ffmpeg and ffprobe must resolve to distinct executables")
    return resolved


def _safe_process_env(temp_root: Path, tools: Mapping[str, Path]) -> dict[str, str]:
    system_root = os.environ.get("SystemRoot") or os.environ.get("WINDIR") or ""
    path_parts = [str(tools["ffmpeg"].parent), str(tools["ffprobe"].parent)]
    if system_root:
        path_parts.append(str(Path(system_root) / "System32"))
    env = {
        "PATH": os.pathsep.join(dict.fromkeys(path_parts)),
        "TEMP": str(temp_root),
        "TMP": str(temp_root),
    }
    if system_root:
        env["SystemRoot"] = system_root
        env["WINDIR"] = system_root
        env["ComSpec"] = str(Path(system_root) / "System32" / "cmd.exe")
    if os.name == "nt":
        env["PATHEXT"] = ".COM;.EXE;.BAT;.CMD"
    return env


def _run_local(
    argv: Sequence[str | os.PathLike[str]],
    *,
    cwd: Path,
    env: Mapping[str, str] | None = None,
    timeout: float = 120.0,
) -> subprocess.CompletedProcess[bytes]:
    command = [os.fspath(value) for value in argv]
    return subprocess.run(
        command,
        cwd=str(cwd),
        env=dict(env) if env is not None else None,
        shell=False,
        close_fds=True,
        check=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=timeout,
    )


@contextmanager
def _local_temp_directory(path: Path) -> Iterator[None]:
    path.mkdir(parents=True, exist_ok=True)
    previous_tempdir = tempfile.tempdir
    previous_temp = os.environ.get("TEMP")
    previous_tmp = os.environ.get("TMP")
    tempfile.tempdir = str(path)
    os.environ["TEMP"] = str(path)
    os.environ["TMP"] = str(path)
    try:
        yield
    finally:
        tempfile.tempdir = previous_tempdir
        if previous_temp is None:
            os.environ.pop("TEMP", None)
        else:
            os.environ["TEMP"] = previous_temp
        if previous_tmp is None:
            os.environ.pop("TMP", None)
        else:
            os.environ["TMP"] = previous_tmp


def _write_tone_wav(path: Path, frequency_hz: float, amplitude: float) -> None:
    duration = 0.24
    frame_count = int(round(duration * SAMPLE_RATE))
    fade_frames = int(round(0.008 * SAMPLE_RATE))
    samples = array("h")
    for index in range(frame_count):
        envelope = min(
            1.0,
            index / max(1, fade_frames),
            (frame_count - 1 - index) / max(1, fade_frames),
        )
        value = amplitude * envelope * math.sin(
            2.0 * math.pi * frequency_hz * index / SAMPLE_RATE
        )
        samples.append(int(max(-1.0, min(1.0, value)) * 32767.0))
    path.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(path), "wb") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(SAMPLE_RATE)
        handle.writeframes(samples.tobytes())


